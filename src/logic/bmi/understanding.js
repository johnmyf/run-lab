/** 解析 **加粗** 分段：返回 [{ text, bold }] */
export function parseBold(text) {
  return String(text)
    .split(/\*\*(.+?)\*\*/g)
    .map((seg, i) => ({ text: seg, bold: i % 2 === 1 }))
}

